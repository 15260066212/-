import { Hono } from 'hono';
import { ContentReviewer } from '@zemingengine/content-reviewer';
import { ContentGenerator } from '@zemingengine/content-generator';
import type { DatabaseAccess } from '../db.js';
import type { ReviewResult } from '@zemingengine/shared';

const MAX_REVIEW_ROUNDS = 3;

export function createReviewRoutes(db: DatabaseAccess): Hono {
  const app = new Hono();
  const reviewer = new ContentReviewer();
  const generator = new ContentGenerator();

  // POST /:articleId - 审核文章
  app.post('/:articleId', async (c) => {
    try {
      const articleId = c.req.param('articleId');
      const article = db.articles.getArticle(articleId);
      if (!article) {
        return c.json({ success: false, error: 'Article not found' }, 404);
      }
      const session = db.sessions.getSession(article.sessionId);
      if (!session) {
        return c.json({ success: false, error: 'Session not found' }, 404);
      }

      const currentRound = (article as any).reviewRound || 0;
      const newRound = currentRound + 1;

      // First round: verify article was generated by DeepSeek API (not fallback template)
      const generationMeta = (article as any).generationMeta as { model?: string } | undefined;
      const isAIGenerated = generationMeta?.model && generationMeta.model !== 'fallback-template-v2';
      const isFallbackTemplate = !isAIGenerated;

      const review = reviewer.review(article, session) as ReviewResult;

      // First round: if article was NOT generated by DeepSeek API, add this as a critical issue
      if (newRound === 1 && isFallbackTemplate) {
        review.passed = false;
        review.issues = [
          ...(review.issues ?? []),
          {
            dimension: 'quality' as any,
            severity: 'high' as const,
            description: '文章未由 DeepSeek API 生成（使用了回退模板），需要重新通过 AI 生成',
          },
        ];
        review.suggestions = [
          ...(review.suggestions ?? []),
          '请检查 DeepSeek API 配置和余额，确保文章由 AI 生成而非使用回退模板',
        ];
      }

      const reviewWithRound = { ...review, round: newRound, isAIGenerated: !!isAIGenerated };
      db.reviews.insertReview(reviewWithRound);

      if (review.passed) {
        db.articles.updateArticle(articleId, { status: 'approved', reviewRound: newRound } as any);
        return c.json({ success: true, data: reviewWithRound });
      }

      // 审核未通过
      if (newRound >= MAX_REVIEW_ROUNDS) {
        // 达到3次上限，转为人工改写
        db.articles.updateArticle(articleId, { status: 'manual_edit', reviewRound: newRound } as any);
        return c.json({
          success: true,
          data: reviewWithRound,
          message: `文章已连续${MAX_REVIEW_ROUNDS}次审核未通过，已转为人工改写状态`,
          manualEdit: true,
        });
      }

      // 未达到上限，根据审核失败原因自动修改文章后重审
      const regenerated = await generator.generate({
        sessionId: article.sessionId,
        platform: article.platform,
        contentType: article.contentType,
        generationRound: article.generationRound,
        reviewFeedback: {
          issues: review.issues,
          suggestions: review.suggestions,
          overallScore: review.overallScore,
        },
        topic: article.title,
      }, session);

      // 更新文章内容
      db.articles.updateArticle(articleId, {
        contentMarkdown: regenerated.article.contentMarkdown,
        contentHtml: regenerated.article.contentHtml,
        contentPlain: regenerated.article.contentPlain,
        tags: regenerated.article.tags,
        summary: regenerated.article.summary,
        wordCount: regenerated.article.wordCount,
        status: 'reviewing',
        reviewRound: newRound,
      } as any);

      // 对修改后的文章重新审核
      const updatedArticle = db.articles.getArticle(articleId);
      if (updatedArticle) {
        const reReview = reviewer.review(updatedArticle, session) as ReviewResult;
        const reReviewWithRound = { ...reReview, round: newRound };
        db.reviews.insertReview(reReviewWithRound);

        if (reReview.passed) {
          db.articles.updateArticle(articleId, { status: 'approved', reviewRound: newRound } as any);
          return c.json({
            success: true,
            data: reReviewWithRound,
            message: `第${newRound}次重审通过（已根据审核反馈自动修改）`,
          });
        }

        if (newRound + 1 >= MAX_REVIEW_ROUNDS) {
          db.articles.updateArticle(articleId, { status: 'manual_edit', reviewRound: newRound } as any);
          return c.json({
            success: true,
            data: reReviewWithRound,
            message: `文章已连续${MAX_REVIEW_ROUNDS}次审核未通过，已转为人工改写状态`,
            manualEdit: true,
          });
        }

        return c.json({
          success: true,
          data: reReviewWithRound,
          message: `第${newRound}次审核未通过，已根据反馈修改文章，可继续点击重新审核`,
          autoFixed: true,
        });
      }

      return c.json({ success: true, data: reviewWithRound });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown error';
      return c.json({ success: false, error: message }, 500);
    }
  });

  // GET /:articleId/latest - 获取最新审核记录
  app.get('/:articleId/latest', (c) => {
    try {
      const articleId = c.req.param('articleId');
      const review = db.reviews.getLatestReview(articleId);
      if (!review) {
        return c.json({ success: false, error: 'Review not found' }, 404);
      }
      return c.json({ success: true, data: review });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown error';
      return c.json({ success: false, error: message }, 500);
    }
  });

  // GET /:articleId - 获取文章的所有审核记录
  app.get('/:articleId', (c) => {
    try {
      const articleId = c.req.param('articleId');
      const reviews = db.reviews.getReviewsByArticle(articleId);
      return c.json({ success: true, data: reviews });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown error';
      return c.json({ success: false, error: message }, 500);
    }
  });

  // POST /:articleId/manual-save - 人工改写后保存并重新审核
  app.post('/:articleId/manual-save', async (c) => {
    try {
      const articleId = c.req.param('articleId');
      const body = await c.req.json();
      const { contentMarkdown, title, summary, tags } = body;

      const article = db.articles.getArticle(articleId);
      if (!article) {
        return c.json({ success: false, error: 'Article not found' }, 404);
      }

      db.articles.updateArticle(articleId, {
        contentMarkdown: contentMarkdown || article.contentMarkdown,
        title: title || article.title,
        summary: summary || article.summary,
        tags: tags || article.tags,
        status: 'reviewing',
      });

      const session = db.sessions.getSession(article.sessionId);
      if (!session) {
        return c.json({ success: false, error: 'Session not found' }, 404);
      }

      const updatedArticle = db.articles.getArticle(articleId);
      if (!updatedArticle) {
        return c.json({ success: false, error: 'Article not found' }, 404);
      }

      const review = reviewer.review(updatedArticle, session) as ReviewResult;
      const newRound = (article as any).reviewRound || 0;
      const reviewWithRound = { ...review, round: newRound + 1 };
      db.reviews.insertReview(reviewWithRound);

      if (review.passed) {
        db.articles.updateArticle(articleId, { status: 'approved', reviewRound: newRound + 1 } as any);
      }

      return c.json({ success: true, data: reviewWithRound });
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown error';
      return c.json({ success: false, error: message }, 500);
    }
  });

  return app;
}
